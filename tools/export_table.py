"""Generate the export table of XMen2Native (phase 5): one entry per global of
game/include/xmen2_globals.h, by name, 68000 address and declared type, which
game/runtime/export.cpp writes into the 68000 RAM image the sync rows are computed from. Build
output, never committed: tools/xmen2check.py build runs it (after the bridges, before cmake).

    uv run tools/export_table.py --out build/native [--src build/handc_src]

Writes OUT/xmen2_export_globals.inc:
    #include "<src>/xmen2.h"                   (the same headers the hand C is built with)
    XG(T, name, addr)                           a global of type T
    XA(T, name, addr, n)                        an array of n T (`extern T name[n];`)
    XU(T, name, addr, bytes)                    an array declared without a length
                                                (`extern T name[];`): its extent is taken to the
                                                next global's address (bytes), whole elements
The declaration is the PC-mode `#define name XM_G(T, 0xADDR)` / `XM_GA(T, 0xADDR)`; the length
comes from the same global's MPW `extern` line. Prints a one-line summary.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common  # noqa: E402

DEFINE = re.compile(r"^#define\s+([A-Za-z_]\w*)\s+XM_G(A?)\((.+),\s*(0x[0-9A-Fa-f]+)\)\s*$")
EXTERN = re.compile(r"^extern\s+(.+?)\s*\b([A-Za-z_]\w*)\s*(?:\[([^\]]*)\])?\s*;")


def parse(header: Path) -> list[dict]:
    """Every global the header declares for PC mode, with its MPW array length."""
    lengths: dict[str, str | None] = {}
    out = []
    for line in header.read_text(encoding="utf-8").splitlines():
        m = EXTERN.match(line.strip())
        if m:
            lengths[m.group(2)] = m.group(3)
            continue
        m = DEFINE.match(line.strip())
        if m:
            name, arr, typ, addr = m.group(1), bool(m.group(2)), m.group(3).strip(), int(m.group(4), 16)
            if not 0xFF0000 <= addr <= 0xFFFFFF:
                sys.exit(f"{header.name}: {name} at ${addr:X} is not in work RAM")
            out.append({"name": name, "array": arr, "type": typ, "addr": addr})
    for g in out:
        n = lengths.get(g["name"], "")
        if g["array"]:
            if g["name"] not in lengths:
                sys.exit(f"{header.name}: {g['name']} (XM_GA) has no MPW extern to give its length")
            g["n"] = (n or "").strip() or None   # None: declared without a length
        elif n:
            sys.exit(f"{header.name}: {g['name']} is XM_G (one value) but its MPW extern is an array")
    return out


def generate(src: Path, out: Path) -> dict:
    gl = parse(src / "xmen2_globals.h")
    starts = sorted({g["addr"] for g in gl})
    L = ["/* xmen2_export_globals.inc - GENERATED by tools/export_table.py from xmen2_globals.h. Do not edit.",
         "   XG(T, name, addr) a global; XA(T, name, addr, n) an array of n; XU(T, name, addr, bytes) an array",
         "   declared without a length, to the next global (game/runtime/export.cpp). */",
         f'#include "{(src / "xmen2.h").as_posix()}"',
         "#define XMEN2_EXPORT_GLOBALS \\"]
    unsized = 0
    for g in sorted(gl, key=lambda g: (g["addr"], g["name"])):
        a = f"0x{g['addr']:06X}u"
        if not g["array"]:
            L.append(f"    XG({g['type']}, {g['name']}, {a}) \\")
        elif g["n"] is not None:
            L.append(f"    XA({g['type']}, {g['name']}, {a}, ({g['n']})) \\")
        else:
            nxt = next((s for s in starts if s > g["addr"]), 0x1000000)
            L.append(f"    XU({g['type']}, {g['name']}, {a}, 0x{nxt - g['addr']:X}u) \\")
            unsized += 1
    L += ["", f"#define XMEN2_EXPORT_GLOBAL_COUNT {len(gl)}", ""]
    out.mkdir(parents=True, exist_ok=True)
    path = out / "xmen2_export_globals.inc"
    data = "\n".join(L).encode("utf-8")
    if not path.exists() or path.read_bytes() != data:   # unchanged: keep the timestamp (no recompile)
        path.write_bytes(data)
    return {"globals": len(gl), "arrays": sum(g["array"] for g in gl), "unsized": unsized, "out": str(path)}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=common.BUILD / "native")
    ap.add_argument("--src", type=Path, default=common.GAME / "include",
                    help="the headers (xmen2check.py build passes its snapshot, build/handc_src)")
    a = ap.parse_args()
    r = generate(a.src.resolve(), a.out)
    print(f"export table: {r['globals']} globals ({r['arrays']} arrays, {r['unsized']} without a length) -> {r['out']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
