"""First draft of the shared headers of the hand-written C (phase 4, criterion D3), from the
disassembly. Run once; afterwards the headers are edited by hand as fields, types and
signatures become understood (they are the C's source of truth, not this script).

    uv run tools/gen_headers.py [--force]

Writes game/include/: xmen2_types.h (the object system: Class, one struct per class
tools/classes.py finds, sized by each class's GetSize), xmen2_globals.h (every A5 global of
ram_globals.csv), xmen2_funcs.h (a prototype per function of functions.csv, signatures
inferred from the frame accesses and the asm headers), xmen2_data.h (ROM data labels).
Inputs come from the working disassembly checkout (common.DISASM_MAIN): build/recomp/,
build/symbols.txt, src/f/, tools/classes.py.
"""
from __future__ import annotations

import argparse
import csv
import re
import struct
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common  # noqa: E402

DIS = common.DISASM_MAIN
INC = common.GAME / "include"
LINK_A6 = 0x4E56


def load_rom() -> bytes:
    return common.ensure_rom().read_bytes()


def functions() -> list[dict]:
    with open(DIS / "build" / "recomp" / "functions.csv", newline="") as f:
        return list(csv.DictReader(f))


def symbols() -> dict[str, int]:
    out = {}
    for line in (DIS / "build" / "symbols.txt").read_text(encoding="utf-8").splitlines():
        n, _, a = line.partition("=$")
        if a:
            out[n.strip()] = int(a.strip(), 16)
    return out


# --- classes --------------------------------------------------------------------------

def class_list(rom: bytes, funcs: list[dict]) -> list[dict]:
    import types
    sys.path.insert(0, str(DIS / "tools"))
    sys.modules.setdefault("m68k", types.ModuleType("m68k"))   # find_classes needs only the ROM
    import classes  # noqa: E402
    found = classes.find_classes(rom)
    L = lambda a: struct.unpack(">I", rom[a:a + 4])[0]
    # struct names: the module prefix of the class's functions whose upper case is the class name
    prefixes = {}
    for f in funcs:
        p = f["name"].split("_")[0]
        prefixes.setdefault(p.upper(), p)
    out = []
    for desc, (name, parent) in found.items():
        cname = prefixes.get(name.replace(" ", "").upper()) or name.title().replace(" ", "")
        get_size = L(desc + 6)
        size = object_size(rom, get_size)
        out.append({"desc": desc, "name": name, "cname": cname, "parent": parent, "size": size,
                    "get_size": get_size})
    by = {c["desc"]: c for c in out}
    for c in out:
        c["parent_c"] = by[c["parent"]]["cname"] if c["parent"] in by else None
    return out


def object_size(rom: bytes, fn: int) -> int | None:
    """GetSize methods: link a6,#0 / moveq #n,d0 | move.l #n,d0 / unlk / rts."""
    if int.from_bytes(rom[fn:fn + 2], "big") != LINK_A6:
        return None
    p = fn + 4
    op = int.from_bytes(rom[p:p + 2], "big")
    if op & 0xFF00 == 0x7000:
        return op & 0xFF
    if op == 0x203C:
        return int.from_bytes(rom[p + 2:p + 6], "big")
    return None


def depth_order(cls: list[dict]) -> list[dict]:
    by = {c["desc"]: c for c in cls}
    done, out = set(), []

    def visit(c):
        if c["desc"] in done:
            return
        if c["parent"] in by:
            visit(by[c["parent"]])
        done.add(c["desc"])
        out.append(c)
    for c in sorted(cls, key=lambda c: c["cname"]):
        visit(c)
    return out


def write_types(rom: bytes, funcs: list[dict]) -> str:
    cls = depth_order(class_list(rom, funcs))
    by = {c["desc"]: c for c in cls}
    lines = [
        "/* xmen2_types.h - the game's records and its object system (hand-written C, phase 4).",
        " *",
        " * The object system is the game's own (MPW C has no C++): an object starts with a pointer",
        " * to its class descriptor {word name offset; parent descriptor; method slots from +6}, and",
        " * a virtual call is (*self->cls->method[n])(self, ...). Every class has a FIELDS macro",
        " * with its parent's fields first, so self->field works at every level of the hierarchy.",
        " * Field names come from what the code does with them (unk_XX = offset XX, not understood",
        " * yet); +$XX comments are byte offsets, checked in PC mode by CHECK_OFFSET.",
        " * First draft generated by tools/gen_headers.py; edited by hand since. */",
        "#ifndef XMEN2_TYPES_H",
        "#define XMEN2_TYPES_H",
        "",
        '#include "xmen2_mem.h"',
        "",
        "#ifdef XMEN2_MPW",
        "#define CHECK_OFFSET(type, field, off)",
        "#define CHECK_SIZE(type, size)",
        "#else",
        "#define CHECK_OFFSET(type, field, off) static_assert(offsetof(type, field) == (off), #type \".\" #field)",
        "#define CHECK_SIZE(type, size) static_assert(sizeof(type) == (size), \"sizeof \" #type)",
        "#endif",
        "",
        "/* A class descriptor (ROM): name offset, parent, then the method slots. */",
        "typedef struct Class {",
        "\ts16 nameOffset;\t\t\t/* +$00 offset of the C-string class name from here */",
        "\tPTR(struct Class) parent;\t/* +$02 */",
        "\tAnyFn method[1];\t\t/* +$06 slot n at +$06 + 4n (the table runs up to the name) */",
        "} Class;",
        "",
    ]
    for c in cls:
        up = c["cname"].upper()
        par = by.get(c["parent"])
        start = (par["size"] or 0) if par else 0
        size = c["size"]
        lines.append(f"/* {c['name']}: descriptor ${c['desc']:06X}" + (f", parent {par['name']}" if par else ", root")
                     + (f", ${size:X} bytes (GetSize ${c['get_size']:06X})" if size else ", size unknown") + " */")
        body = [f"{par['cname'].upper()}_FIELDS"] if par else ["PTR(Class) cls;\t\t\t/* +$00 class descriptor */"]
        if not par and size and size > 4:
            body.append(f"u8 unk_04[0x{size - 4:X}];\t\t/* +$04 */")
        elif par and size and size > start:
            body.append(f"u8 unk_{start:02X}[0x{size - start:X}];\t\t/* +${start:02X} */")
        lines.append(f"#define {up}_FIELDS \\")
        lines += [f"\t{b} \\" for b in body[:-1]]
        lines.append(f"\t{body[-1]}")
        lines.append(f"typedef struct {c['cname']} {{ {up}_FIELDS }} {c['cname']};")
        if size:
            lines.append(f"CHECK_SIZE({c['cname']}, 0x{size:X});")
        lines.append("")
    lines += ["#endif /* XMEN2_TYPES_H */", ""]
    return "\n".join(lines)


# --- globals --------------------------------------------------------------------------

KIND = {"word": "s16", "byte": "u8", "long": "s32", "ptr": "PTR(void)"}


def write_globals() -> str:
    with open(DIS / "build" / "recomp" / "ram_globals.csv", newline="") as f:
        rows = list(csv.DictReader(f))
    rows.sort(key=lambda r: int(r["ram_addr"], 16))
    lines = [
        "/* xmen2_globals.h - the game's A5-world RAM globals, under the disassembly's names.",
        " *",
        " * MPW: plain externs, linked to their A5 offsets (cc.py --match-recomp checks every",
        " * reference). PC: the same names on the emulated work RAM, as the 68000 addresses the",
        " * original took them ($FFFFxxxx: A5-relative), so &g_X keeps its original value.",
        " * Types are the disassembly's (word/byte/long/ptr); arrays and records get their real",
        " * types as the code using them is written. First draft by tools/gen_headers.py.",
        " */",
        "#ifndef XMEN2_GLOBALS_H",
        "#define XMEN2_GLOBALS_H",
        "",
        '#include "xmen2_types.h"',
        "",
        "#ifdef XMEN2_MPW",
        "#define GLOBAL(type, name, addr)              extern type name",
        "#define GLOBAL_ARRAY(type, name, n, addr)     extern type name[n]",
        "#else",
        "#define GLOBAL(type, name, addr)              /* name = *(type *)$addr */",
        "#define GLOBAL_ARRAY(type, name, n, addr)     /* name = (type *)$addr */",
        "#define XM_G(type, addr)                      (*(type *)(XM_RAM_FFFF + ((addr) & 0xFFFF)))",
        "#define XM_GA(type, addr)                     ((type *)(XM_RAM_FFFF + ((addr) & 0xFFFF)))",
        "#endif",
        "",
    ]
    for r in rows:
        name, addr, cmt = r["name"], int(r["ram_addr"], 16), r["comment"].replace("*/", "* /")
        m = re.match(r"\s*([a-z]+)\s*:", cmt)
        kind = m.group(1) if m else ""
        typ = KIND.get(kind)
        n = None
        if typ is None:
            m2 = re.match(r"\s*(\d+)\s+(word|byte|long|ptr)s?\b", cmt)
            if m2:
                n, typ = int(m2.group(1)), KIND[m2.group(2)]
            else:
                typ, n = "u8", 0   # extent unknown: an array of bytes
        lines.append(f"/* ${addr:06X} {cmt} */")
        if n is None:
            lines.append("#ifdef XMEN2_MPW")
            lines.append(f"extern {typ} {name};")
            lines.append("#else")
            lines.append(f"#define {name} XM_G({typ}, 0x{addr:06X})")
            lines.append("#endif")
        else:
            dim = str(n) if n else ""
            lines.append("#ifdef XMEN2_MPW")
            lines.append(f"extern {typ} {name}[{dim}];")
            lines.append("#else")
            lines.append(f"#define {name} XM_GA({typ}, 0x{addr:06X})")
            lines.append("#endif")
    lines += ["", "#endif /* XMEN2_GLOBALS_H */", ""]
    return "\n".join(lines)


# --- functions ------------------------------------------------------------------------

ARG_RE = re.compile(r"(-?\$?[0-9A-Fa-f]+)\(a6\)")
SP_ARG_RE = re.compile(r"(\$?[0-9A-Fa-f]+)\(a7\)")
SIZE_RE = re.compile(r"^\s*([a-z]+)(?:\.([bwl]))?\s")
CALL_RE = re.compile(r"^\s+(jsr|bsr\S*|pea\S*|lea\S*|jmp)\s+([A-Za-z_]\w*)")


def callable_names(funcs: list[dict]) -> set[str]:
    """Functions the code calls, jumps to as a whole or takes the address of: jsr/bsr/jmp/pea/
    lea by name, jump-table entries, class method slots. The others are only branched into
    (switch cases, blocks split off their function)."""
    names = {f["name"] for f in funcs}
    out = set()
    for p in (DIS / "src" / "f").glob("*.asm"):
        for line in p.read_text(encoding="utf-8").splitlines():
            m = CALL_RE.match(line)
            if m and m.group(2) in names:
                out.add(m.group(2))
    for line in (DIS / "src" / "jumptable.asm").read_text(encoding="utf-8").splitlines():
        m = re.match(r"\s*jtentry\s+(\w+)", line)
        if m:
            out.add(m.group(1))
    return out


def infer_signature(asm: str, rom: bytes, addr: int, called: bool) -> tuple[str, list[str], str]:
    """(return type, parameter types, note) from the frame accesses and the header."""
    hdr = "\n".join(l for l in asm.splitlines() if l.startswith(";"))
    framed = int.from_bytes(rom[addr:addr + 2], "big") == LINK_A6
    if not framed and (not called or "registers/frame of" in hdr or "not a separate function" in hdr):
        return "void", [], "fragment"
    slots: dict[int, str] = {}
    arg_re, base = (ARG_RE, 8) if framed else (SP_ARG_RE, 4)
    if True:
        for line in asm.splitlines():
            if line.startswith(";"):
                continue
            for m in arg_re.finditer(line):
                v = m.group(1)
                off = -int(v.lstrip("-$"), 16) if v.startswith("-") else int(v.lstrip("$"), 16)
                if off < base:
                    continue
                k = (off - base) // 4
                if k > 12:
                    continue
                sm = SIZE_RE.match(line)
                op, sz = (sm.group(1), sm.group(2)) if sm else ("", "")
                kind = "long"
                if op in ("movea", "lea", "pea") or (sz == "l" and ",a" in line.split(m.group(0))[1][:3]):
                    kind = "ptr"
                elif off % 4 == 2:
                    kind = "short"
                elif off % 4 == 3:
                    kind = "char"
                elif sz == "w":
                    kind = "short"
                if slots.get(k) not in ("ptr",):
                    slots[k] = kind if slots.get(k) in (None, "long") else slots[k]
    params = []
    for k in range(max(slots) + 1 if slots else 0):
        params.append({"ptr": "void *", "short": "short", "char": "char", "long": "long"}.get(slots.get(k), "long"))
    out = re.search(r"^; Out:\s*(.*)$", hdr, re.M)
    ret = "long"
    if out:
        o = out.group(1).strip().lower()
        if o.startswith("none") or o == "-":
            ret = "void"
        elif re.search(r"\bd0\b[^;]*\bword\b|d0\.w", o):
            ret = "short"
        elif re.search(r"\bd0\b[^;]*\bbyte\b|d0\.b", o):
            ret = "char"
    return ret, params, "" if framed else "asm"


def write_funcs(rom: bytes, funcs: list[dict]) -> str:
    lines = [
        "/* xmen2_funcs.h - a prototype for every function of the disassembly (hand-written C, phase 4).",
        " *",
        " * The calling convention is MPW C's for all of them: every argument in a 4-byte slot,",
        " * pushed right to left, the caller pops; result in d0; d3-d7/a2-a4 preserved. C calls a",
        " * function by these names whether it is written in C yet or still generated code (the",
        " * bridge decides), so converting a callee never changes its callers. Functions marked",
        " * `fragment` are pieces the disassembly split off a C function (switch cases, blocks):",
        " * in C they are code inside their parent, never called. `asm` ones have no MPW frame.",
        " * The first draft's signatures are inferred from the frame accesses (arguments: their",
        " * count and widths; `void *` where the slot was loaded into an address register) and the",
        " * asm header's Out line; a function's C fixes its own prototype here.",
        " */",
        "#ifndef XMEN2_FUNCS_H",
        "#define XMEN2_FUNCS_H",
        "",
        '#include "xmen2_types.h"',
        "",
    ]
    called = callable_names(funcs)
    for f in sorted(funcs, key=lambda f: int(f["addr"], 16)):
        addr = int(f["addr"], 16)
        p = DIS / "src" / "f" / f"{f['addr']}.asm"
        asm = p.read_text(encoding="utf-8") if p.exists() else ""
        ret, params, note = infer_signature(asm, rom, addr, f["name"] in called)
        args = ", ".join(params) if params else "void"
        tag = f" {note}" if note else ""
        lines.append(f"{ret} {f['name']}({args});\t/* ${f['addr']}{tag} */")
    lines += ["", "#endif /* XMEN2_FUNCS_H */", ""]
    return "\n".join(lines)


# --- ROM data -------------------------------------------------------------------------

DATA_PREFIXES = ("Tbl_", "Str_", "Pal_", "Art_", "Map_", "Snd_", "Lvl_")


def write_data(funcs: list[dict]) -> str:
    syms = symbols()
    fnames = {f["name"] for f in funcs}
    data = sorted((a, n) for n, a in syms.items()
                  if n.startswith(DATA_PREFIXES) and n not in fnames and a < 0x200000)
    lines = [
        "/* xmen2_data.h - ROM data the C names (tables, strings, palettes...), by disassembly label.",
        " *",
        " * MPW: data in the code segments is named as code, as the original did (`extern void",
        " * Tbl_X();`): the linker resolves it PC-relative, or to a jump-table entry from another",
        " * segment (read the real address with CODEPTR()/CLASS()). PC: the ROM bytes at the label.",
        " * Generated by tools/gen_headers.py from build/symbols.txt.",
        " */",
        "#ifndef XMEN2_DATA_H",
        "#define XMEN2_DATA_H",
        "",
        '#include "xmen2_mem.h"',
        "",
        "#ifdef XMEN2_MPW",
    ]
    lines += [f"extern void {n}();" for a, n in data]
    lines.append("#else")
    lines += [f"#define {n} (xm::rom(0x{a:06X}))" for a, n in data]
    lines += ["#endif", "", "#endif /* XMEN2_DATA_H */", ""]
    return "\n".join(lines)


UMBRELLA = """/* xmen2.h - everything the hand-written C sees: include this, nothing else. */
#ifndef XMEN2_H
#define XMEN2_H
#include "xmen2_mem.h"
#include "xmen2_types.h"
#include "xmen2_globals.h"
#include "xmen2_data.h"
#include "xmen2_funcs.h"
#endif
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--force", action="store_true", help="overwrite existing headers")
    ap.add_argument("--only", nargs="*", default=[], help="types globals funcs data")
    a = ap.parse_args()
    rom = load_rom()
    funcs = functions()
    INC.mkdir(parents=True, exist_ok=True)
    jobs = {"types": ("xmen2_types.h", lambda: write_types(rom, funcs)),
            "globals": ("xmen2_globals.h", write_globals),
            "funcs": ("xmen2_funcs.h", lambda: write_funcs(rom, funcs)),
            "data": ("xmen2_data.h", lambda: write_data(funcs)),
            "umbrella": ("xmen2.h", lambda: UMBRELLA)}
    for key, (name, make) in jobs.items():
        if a.only and key not in a.only:
            continue
        p = INC / name
        if p.exists() and not a.force:
            print(f"{p.name}: exists (use --force)")
            continue
        p.write_text(make(), encoding="utf-8", newline="\n")
        print(f"wrote {p}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
