"""Regenerate the recompiler's discovery inputs (game/xmen2.*) from the disassembly.

    uv run tools/sync_disasm.py

Builds the pinned xmen2disasm submodule (byte-identical check included) and exports its
phase-1 handoff (tools/handoff.py -> build/recomp/), then writes:
  game/xmen2.code_addrs.txt   every instruction start
  game/xmen2.seeds.toml       [functions] extra = every function entry
  game/xmen2.jtstubs.toml     [functions] extra = jump-table stubs ($222+8i) whose target is code
  game/xmen2.functions.csv    addr,name,end,purpose (names for logs, crash reports, K3)
The generated files are committed: a build needs only the ROM, not a built disassembly.
"""
from __future__ import annotations

import csv
import os
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common  # noqa: E402

# (start, end, stride, evidence): runs of identical blocks entered by a computed jump at any
# block boundary. Each block start becomes a label entry (xmen2.labels.toml).
COMPUTED_ENTRY_RUNS = [
    (0x1FC8FE, 0x1FD43E, 18, "Scaler_RowBlocks + Scaler_RowBlocksLast80: 160 18-byte blocks entered "
                            "at $1FC8FE + (160 - width/2)*18 by Scaler_BeginPass (xmen2disasm NOTES)"),
]


def main() -> int:
    dis = common.DISASM
    rom = common.ensure_rom()
    env = {**os.environ, "XMEN2_ROM": str(rom)}
    for tool in ("tools/build.py", "tools/handoff.py"):
        r = subprocess.run(["uv", "run", tool], cwd=dis, env=env)
        if r.returncode != 0:
            print(f"FAIL: {tool} in {dis}")
            return 1
    hand = dis / "build" / "recomp"
    g = common.GAME
    shutil.copyfile(hand / "code_addrs.txt", g / "xmen2.code_addrs.txt")
    shutil.copyfile(hand / "functions.csv", g / "xmen2.functions.csv")
    seeds = (hand / "seeds.toml").read_text()
    (g / "xmen2.seeds.toml").write_text(seeds, newline="\n")
    with open(hand / "jumptable.csv", newline="") as f:
        stubs = [r for r in csv.DictReader(f) if r["kind"] == "code"]
    lines = ["# Generated by tools/sync_disasm.py from xmen2disasm build/recomp/jumptable.csv.",
             "# A5 jump-table entries are `bra.s *` + `jmp target.l`; every `jsr $22+8i(a5)` lands",
             "# on the jmp at $222+8i. Only entries whose target is code are listed (the rest are",
             "# data pointers read through the table, never called).",
             "[functions]", "extra = ["]
    lines += [f"  0x{r['jmp_addr']},  # jt {r['index']} -> {r['target']} {r['target_name']}" for r in stubs]
    lines.append("]")
    (g / "xmen2.jtstubs.toml").write_text("\n".join(lines) + "\n", newline="\n")

    # Interior code labels: every disassembly label on an instruction start that is not a
    # function entry (branch targets, switch cases, jump-table and AI-script targets). They
    # seed the recompiler's CFG walk inside each function, and in exact mode they are the
    # case set a computed JMP is compiled against.
    code = {int(x, 16) for x in (hand / "code_addrs.txt").read_text().split()}
    with open(hand / "functions.csv", newline="") as f:
        starts = {int(r["addr"], 16) for r in csv.DictReader(f)}
    syms: dict[int, str] = {}
    for line in (dis / "build" / "symbols.txt").read_text().splitlines():
        n, _, a = line.partition("=$")
        if a:
            syms.setdefault(int(a, 16), n)
    inter = set(a for a in syms if a in code and a not in starts)
    # Computed entries the disassembly documents but does not label one by one.
    for lo, hi, stride, why in COMPUTED_ENTRY_RUNS:
        run = [a for a in range(lo, hi, stride) if a in code and a not in starts]
        if len(run) != (hi - lo) // stride - sum(1 for a in range(lo, hi, stride) if a in starts):
            sys.exit(f"computed-entry run ${lo:06X}: not all block starts are instruction starts ({why})")
        inter.update(run)
    inter = sorted(inter)
    lab = ["# Generated by tools/sync_disasm.py: interior code labels of the disassembly.",
           "[functions]", "extra_seeds = ["]
    lab += [f"  0x{a:06X},  # {syms.get(a, 'computed-entry block')}" for a in inter]
    lab.append("]")
    (g / "xmen2.labels.toml").write_text("\n".join(lab) + "\n", newline="\n")
    print(f"synced: {len(stubs)} jump-table stubs, "
          f"{sum(1 for _ in open(g / 'xmen2.functions.csv')) - 1} functions")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
