/* start_stage's names as places: "avalon_a4" -> "Avalon A4 (Magneto)" */
std::string stage_label(const std::string &v)
{
    static const char *const worlds[][2] = {{"sentinels", "Sentinels"}, {"avalon", "Avalon"}, {"banimaza", "Bani Maza"},
                                            {"savage", "Savage Land"}, {"space", "Space"}, {"clone", "Clone factory"}};
    static const char *const bosses[][2] = {{"avalon_a4", " (Magneto)"}, {"banimaza_a2", " (Apocalypse)"}, {"clone_a5", " (last stage)"}};
    size_t u = v.find('_');
    std::string w = v.substr(0, u), name = v;
    for (auto &p : worlds)
        if (w == p[0]) name = p[1];
    if (u == std::string::npos) return name + " (from its briefing)";
    std::string st = v.substr(u + 1);
    for (char &c : st) c = (char)toupper((unsigned char)c);
    name += " " + st;
    for (auto &b : bosses)
        if (v == b[0]) name += b[1];
    return name;
}

std::string value_label(int i, const std::string &v)
{
    const char *key = options_name(i);
    if (const Shown *s = shown(key))
        for (const ValLabel &l : s->vals)
            if (v == l.v) return l.label;
    if (!strcmp(key, "start_stage")) return stage_label(v);
    if (!strcmp(key, "high_fps")) return v + " Hz";
    return v;
}

