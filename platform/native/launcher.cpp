/* An event while a box waits for its input: true when the box took it (ImGui doesn't see it). Key-ups
   always go on to ImGui, so a key that started the wait isn't left held there. */
bool capture_event(State &S, const SDL_Event &e)
{
    if (!S.cap) return false;
    int p = S.cap_player, b = S.cap_button, s = S.cap_slot;
    if (e.type == SDL_KEYDOWN) {
        if (e.key.repeat) return true;
        int sc = e.key.keysym.scancode;
        if (sc == SDL_SCANCODE_ESCAPE) S.ctl_note = "Cancelled: the box is as it was.";
        else if (sc == SDL_SCANCODE_BACKSPACE || sc == SDL_SCANCODE_DELETE) { cell_clear(p, b, s, S.cap_pad); S.ctl_note = "Cleared."; }
        else if (S.cap_pad) { S.ctl_note = "That's a key: this box takes a controller's button or stick (Esc cancels)."; return true; }
        else S.ctl_note = controls_bind_key(p, b, s, sc);
        S.cap = false;
        return true;
    }
    if (e.type == SDL_TEXTINPUT) return true;
    PadIn in;
    if (controls_capture_pad(e, &in)) {
        S.nav_hold = true;
        if (!S.cap_pad) { S.ctl_note = "That's a controller: this box takes a key. Use a Controller box (Esc cancels)."; return true; }
        S.ctl_note = controls_bind_pad(p, b, s, in);
        S.cap = false;
        return true;
    }
    if (e.type == SDL_CONTROLLERBUTTONDOWN || e.type == SDL_CONTROLLERAXISMOTION) return true;
    if (e.type == SDL_MOUSEBUTTONDOWN) { S.cap = false; S.ctl_note.clear(); }   /* a click elsewhere: given up (the click goes on) */
    return false;
}

void bind_cell(State &S, int p, int b, int slot, bool pad, float w)
{
    ImGui::PushID(slot + (pad ? 2 : 0));
    bool waiting = S.cap && S.cap_player == p && S.cap_button == b && S.cap_slot == slot && S.cap_pad == pad;
    std::string label = pad ? controls_pad_label(g_controls[p].pad[b][slot], p) : controls_key_label(g_controls[p].key[b][slot]);
    bool empty = label.empty();
    if (waiting) label = (SDL_GetTicks() / 400) % 2 ? (pad ? "press a button..." : "press a key...") : "";
    else if (empty) label = "";
    int colors = 0;
    if (waiting) {
        ImGui::PushStyleColor(ImGuiCol_Button, C_ACCENT);
        ImGui::PushStyleColor(ImGuiCol_ButtonHovered, C_ACCENT);
        ImGui::PushStyleColor(ImGuiCol_Text, C_ON_ACCENT);
        colors = 3;
    } else if (empty) {
        ImGui::PushStyleColor(ImGuiCol_Button, hex(0x313157));
        ImGui::PushStyleColor(ImGuiCol_Text, C_DIM);
        colors = 2;
    }
    if (ImGui::Button((label + "##c").c_str(), ImVec2(w, 0)) && !waiting) capture_start(S, p, b, slot, pad);
    ImGui::PopStyleColor(colors);
    if (!S.cap) {
        bool clear = ImGui::IsItemClicked(ImGuiMouseButton_Right);
        if (ImGui::IsItemFocused())
            clear |= ImGui::IsKeyPressed(ImGuiKey_Delete) || ImGui::IsKeyPressed(ImGuiKey_Backspace) ||
                     ImGui::IsKeyPressed(ImGuiKey_GamepadFaceLeft, false);
        if (clear && !empty) { cell_clear(p, b, slot, pad); S.ctl_note = "Cleared."; }
    }
    if (ImGui::IsItemHovered() && !S.cap)
        ImGui::SetTooltip(pad ? "Click, then press a button or move a stick on a controller.\nRight-click or Delete clears it."
                              : "Click, then press a key.\nRight-click or Delete clears it.");
    ImGui::PopID();
}

