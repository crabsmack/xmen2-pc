bool launcher_run(const std::string &rom, LaunchPlan *plan)
{
    const char *test = getenv("XMEN2_LAUNCHER_TEST");
    std::vector<std::string> script;
    if (test && *test) {
        FILE *f = fopen(test, "r");
        if (!f) { fprintf(stderr, "[launcher] cannot read %s\n", test); exit(2); }
        char line[1024];
        while (fgets(line, sizeof line, f)) {
            std::string l = line;
            while (!l.empty() && (l.back() == '\n' || l.back() == '\r')) l.pop_back();
            if (!l.empty() && l[0] != '#') script.push_back(l);
        }
        fclose(f);
        SDL_SetHint(SDL_HINT_RENDER_DRIVER, "software");
    }
    if (SDL_InitSubSystem(SDL_INIT_VIDEO | SDL_INIT_GAMECONTROLLER | SDL_INIT_EVENTS) != 0) {
        fprintf(stderr, "[launcher] SDL: %s; starting the game without it\n", SDL_GetError());
        plan->rom = rom;
        plan->netplay.clear();
        return !rom.empty() || (fprintf(stderr, "[launcher] no ROM\n"), false);
    }
    SDL_SetHint(SDL_HINT_IME_SHOW_UI, "1");
    int w = 1100, h = 760;
    SDL_Rect usable;
    if (SDL_GetDisplayUsableBounds(0, &usable) == 0) {   /* a small screen (a handheld): what fits */
        if (w > usable.w - 20) w = usable.w - 20;
        if (h > usable.h - 50) h = usable.h - 50;
    }
    Uint32 wf = SDL_WINDOW_RESIZABLE | (script.empty() ? 0 : SDL_WINDOW_HIDDEN);
    SDL_Window *win = SDL_CreateWindow("X-Men 2: Clone Wars", SDL_WINDOWPOS_CENTERED, SDL_WINDOWPOS_CENTERED, w, h, wf);
    SDL_Renderer *r = win ? SDL_CreateRenderer(win, -1, script.empty() ? SDL_RENDERER_ACCELERATED | SDL_RENDERER_PRESENTVSYNC
                                                                    : SDL_RENDERER_SOFTWARE) : nullptr;
    if (win && !r) r = SDL_CreateRenderer(win, -1, SDL_RENDERER_SOFTWARE);
    if (!win || !r) {
        fprintf(stderr, "[launcher] no window: %s; starting the game without it\n", SDL_GetError());
        if (win) SDL_DestroyWindow(win);
        plan->rom = rom;
        plan->netplay.clear();
        return !rom.empty();
    }
    SDL_SetWindowMinimumSize(win, 900, 620);

    IMGUI_CHECKVERSION();
    ImGui::CreateContext();
    ImGuiIO &io = ImGui::GetIO();
    io.IniFilename = nullptr;
    io.LogFilename = nullptr;
    io.ConfigFlags |= ImGuiConfigFlags_NavEnableKeyboard | ImGuiConfigFlags_NavEnableGamepad;
    ImFontConfig cfg;
    cfg.FontDataOwnedByAtlas = false;
    io.Fonts->AddFontFromMemoryTTF((void *)k_font_karla, (int)sizeof k_font_karla, 19, &cfg);
    g_title_font = io.Fonts->AddFontFromMemoryTTF((void *)k_font_roboto, (int)sizeof k_font_roboto, 30, &cfg);
    theme();
    ImGui_ImplSDL2_InitForSDLRenderer(win, r);
    ImGui_ImplSDLRenderer2_Init(r);

    State S;
    load(S, rom);
    size_t step = 0;
    bool done = false, go = false;
    while (!done) {
        SDL_Event e;
        while (SDL_PollEvent(&e)) {
            ImGui_ImplSDL2_ProcessEvent(&e);
            if (e.type == SDL_QUIT || (e.type == SDL_WINDOWEVENT && e.window.event == SDL_WINDOWEVENT_CLOSE)) S.press = PRESS_QUIT;
        }
        std::string shot;
        if (step < script.size()) test_command(S, script[step++], &shot);
        else if (!script.empty() && S.press == PRESS_NONE) {
            fprintf(stderr, "[launcher] test script ended without a press\n");
            S.press = PRESS_QUIT;
        }
        ImGui_ImplSDLRenderer2_NewFrame();
        ImGui_ImplSDL2_NewFrame();
        ImGui::NewFrame();
        frame(S);
        ImGui::Render();
        SDL_SetRenderDrawColor(r, 0x1a, 0x1a, 0x2e, 255);
        SDL_RenderClear(r);
        ImGui_ImplSDLRenderer2_RenderDrawData(ImGui::GetDrawData(), r);
        if (!shot.empty()) save_shot(r, shot.c_str());
        SDL_RenderPresent(r);
        if (S.press == PRESS_QUIT) done = true;
        else if (S.press != PRESS_NONE) {
            if (make_plan(S, plan)) {
                if (!save(S)) fprintf(stderr, "[launcher] could not write xmen2.ini beside the program\n");
                go = done = true;
            }
            S.press = PRESS_NONE;
        }
        if (script.empty() && (SDL_GetWindowFlags(win) & SDL_WINDOW_MINIMIZED)) SDL_Delay(50);
    }
    ImGui_ImplSDLRenderer2_Shutdown();
    ImGui_ImplSDL2_Shutdown();
    ImGui::DestroyContext();
    SDL_DestroyRenderer(r);
    SDL_DestroyWindow(win);
    return go;
}
