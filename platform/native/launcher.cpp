/* launcher.cpp - the start window (GitHub issue #1): the ROM, the options and online play without the
 * command line. Shown on a played start with no ROM on the command line (a double-click), unless
 * xmen2.ini's [launcher] show = 0; --launcher shows it anyway, --no-launcher skips it once. Dear ImGui
 * (platform/native/external/imgui, MIT) on its own SDL window, closed before the game's opens.
 *
 * It changes nothing the command line can't: the options go to xmen2.ini's [options] (options.cpp) and
 * online play becomes the same --netplay arguments (netplay.cpp), so the game itself never knows a
 * launcher ran. Layout A (tabs: Play, Options, Online), theme "Cerebro" (the Cerebro screen's bezel
 * colours, sampled from rendered frames), chosen by the user from mock-ups (2026-11-18).
 *
 * Testing (no person): XMEN2_LAUNCHER_TEST=FILE runs one command per frame on a hidden window (with
 * SDL_VIDEODRIVER=dummy, headless): `tab play|options|online`, `mode host|join`, `set KEY VALUE` (an
 * option), `field players|connection|port|host|seat|dir|code|router VALUE`, `rom PATH`, `show 0|1`,
 * `focus KEY`, `shot FILE.bmp`, `press play|host|join|cancel|quit`; for join codes (room.cpp) `wait
 * open|guestsN|seated|error|idle|sleep [SECONDS]` (holds the script until then; 30 s), `code-to FILE` (the
 * host's code) and `how upnp|stun|...` (the router's answer as shown); for the Controls page (`tab
 * controls`) `player N`, `bind P BUTTON key|key2|pad|pad2 INPUT|none`, `capture P BUTTON key|pad` (a box
 * waiting), `keys P arrows|wasd|none`, `controller P auto|none|GUID`, `deadzone P N`, `reset P`, and a
 * virtual controller: `vpad`, `vpress BUTTON 0|1`, `vaxis AXIS VALUE` (SDL's names). main.cpp's
 * XMEN2_LAUNCHER_DRYRUN=1 prints the plan instead of starting the game.
 *
 * The Controls page (controls.cpp): per player, the controller (any, in plug-in order; a particular one;
 * none), a keyboard layout, and two keys and two controller inputs for each Genesis button, set by
 * clicking a box and pressing the key or button; a light per button shows what the game would get.
 *
 * Online with a join code (the default): the host's GET A CODE opens a room (room.cpp: its port, its
 * router asked, a code of its addresses); a joiner pastes the code and gets its seat from the host; the
 * game starts when every seat is taken (a second later) or at the host's START NOW, each launcher then
 * handing its game the --netplay arguments the room settled.
 */
