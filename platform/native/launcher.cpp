void check_rom(State &S)
{
    if (!S.rom[0]) { S.rom_why = "Choose your ROM of the game (the USA/Europe cartridge): Browse..."; return; }
    std::string why = rom_check_path(S.rom);
    if (why.empty()) S.rom_why.clear();
    else if (why.compare(0, 6, "cannot") == 0) S.rom_why = "That file can't be opened.";
    else S.rom_why = "That file isn't X-Men 2: Clone Wars (USA/Europe). A zipped ROM has to be unzipped first; "
                     "other versions of the cartridge aren't supported.";
}

/* a virtual adapter (Hyper-V / WSL, VirtualBox, VMware, Docker): no address a friend can reach */
bool virtual_adapter(const std::string &name)
{
    static const char *const marks[] = {"vEthernet", "Hyper-V", "VirtualBox", "VMware", "docker", "virbr", "veth", "br-", "Loopback"};
    for (const char *m : marks)
        if (name.find(m) != std::string::npos) return true;
    return false;
}

/* This PC's IPv4 addresses for the guests: loopback left out; 100.64.0.0/10 is Tailscale's (CGNAT) range */
std::vector<LocalAddr> local_addresses()
{
    std::vector<LocalAddr> out;
    auto add = [&](uint32_t a, const std::string &name) {   /* a: host byte order */
        if ((a >> 24) == 127 || (a >> 16) == 0xA9FE) return;   /* loopback, link-local */
        char ip[32];
        snprintf(ip, sizeof ip, "%u.%u.%u.%u", a >> 24, (a >> 16) & 255, (a >> 8) & 255, a & 255);
        bool priv = (a >> 24) == 10 || (a >> 20) == 0xAC1 || (a >> 16) == 0xC0A8;
        bool cgnat = (a >> 22) == (100u << 2 | 1);   /* 100.64.0.0/10 */
        std::string what = cgnat ? "a VPN such as Tailscale (" + name + ")"
                         : priv  ? "this network (" + name + ")"
                                 : "the internet (" + name + "; needs the port forwarded)";
        out.push_back({ip, what, a});
    };
#ifdef _WIN32
    ULONG size = 16384;
    std::vector<uint8_t> buf(size);
    ULONG flags = GAA_FLAG_SKIP_ANYCAST | GAA_FLAG_SKIP_MULTICAST | GAA_FLAG_SKIP_DNS_SERVER;
    if (GetAdaptersAddresses(AF_INET, flags, nullptr, (IP_ADAPTER_ADDRESSES *)buf.data(), &size) == ERROR_BUFFER_OVERFLOW) {
        buf.resize(size);
    }
    if (GetAdaptersAddresses(AF_INET, flags, nullptr, (IP_ADAPTER_ADDRESSES *)buf.data(), &size) == NO_ERROR) {
        for (IP_ADAPTER_ADDRESSES *a = (IP_ADAPTER_ADDRESSES *)buf.data(); a; a = a->Next) {
            if (a->OperStatus != IfOperStatusUp) continue;
            char name[256] = "", desc[256] = "";
            WideCharToMultiByte(CP_UTF8, 0, a->FriendlyName, -1, name, sizeof name, nullptr, nullptr);
            WideCharToMultiByte(CP_UTF8, 0, a->Description, -1, desc, sizeof desc, nullptr, nullptr);
            if (virtual_adapter(name) || virtual_adapter(desc)) continue;
            for (IP_ADAPTER_UNICAST_ADDRESS *u = a->FirstUnicastAddress; u; u = u->Next) {
                if (u->Address.lpSockaddr->sa_family != AF_INET) continue;
                const uint8_t *b = (const uint8_t *)&((sockaddr_in *)u->Address.lpSockaddr)->sin_addr;
                add((uint32_t)b[0] << 24 | (uint32_t)b[1] << 16 | (uint32_t)b[2] << 8 | b[3], name);
            }
        }
    }
#else
    struct ifaddrs *ifs = nullptr;
    if (getifaddrs(&ifs) == 0) {
        for (struct ifaddrs *i = ifs; i; i = i->ifa_next) {
            if (!i->ifa_addr || i->ifa_addr->sa_family != AF_INET || !(i->ifa_flags & IFF_UP) || (i->ifa_flags & IFF_LOOPBACK) ||
                virtual_adapter(i->ifa_name)) continue;
            add(ntohl(((struct sockaddr_in *)i->ifa_addr)->sin_addr.s_addr), i->ifa_name);
        }
        freeifaddrs(ifs);
    }
#endif
    return out;
}

