const float LABEL_W = 300, FIELD_W = 360;

void focus_help(State &S, const char *key)
{
    if (ImGui::IsItemHovered() || ImGui::IsItemFocused()) S.focus = key;
}

void option_row(State &S, int i)
{
    const char *key = options_name(i);
    const Shown *sh = shown(key);
    std::string cur = options_get(i);
    std::vector<std::string> vals = options_values(i);
    bool changed = cur != vals[0];
    ImGui::PushID(key);
    ImGui::AlignTextToFramePadding();
    ImGui::TextUnformatted(sh ? sh->label : key);
    if (changed) { ImGui::SameLine(); ImGui::TextColored(C_TITLE, "*"); }
    ImGui::SameLine(LABEL_W);
    ImGui::SetNextItemWidth(FIELD_W);
    if (sh && sh->checkbox) {
        bool b = cur == "1";
        if (ImGui::Checkbox(b ? "On" : "Off", &b)) options_set(i, b ? "1" : "0");
    } else {
        if (std::find(vals.begin(), vals.end(), cur) == vals.end()) vals.push_back(cur);   /* a value from the file */
        if (ImGui::BeginCombo("##v", value_label(i, cur).c_str())) {
            for (const std::string &v : vals) {
                bool sel = v == cur;
                if (ImGui::Selectable(value_label(i, v).c_str(), sel)) options_set(i, v);
                if (sel) ImGui::SetItemDefaultFocus();
            }
            ImGui::EndCombo();
        }
    }
    focus_help(S, key);
    ImGui::PopID();
}

/* the options in the launcher's order (shown_table's), then any it has no entry for (a new option shows
   up in "Other" with options.cpp's own description until it gets one) */
std::vector<int> display_order()
{
    std::vector<int> o;
    for (const Shown &s : shown_table())
        for (int i = 0; i < options_count(); i++)
            if (!strcmp(options_name(i), s.key)) o.push_back(i);
    for (int i = 0; i < options_count(); i++)
        if (!shown(options_name(i))) o.push_back(i);
    return o;
}

const char *group_of(int i)
{
    const Shown *s = shown(options_name(i));
    return s ? s->group : "Other";
}

void options_page(State &S, float h)
{
    ImGui::BeginChild("opts", ImVec2(0, h - 96));
    for (const char *g : k_groups) {
        bool any = false;
        for (int i = 0; i < options_count(); i++) any |= !strcmp(group_of(i), g);
        if (!any) continue;
        ImGui::Spacing();
        ImGui::PushStyleColor(ImGuiCol_Text, C_ACCENT);
        ImGui::SeparatorText(g);
        ImGui::PopStyleColor();
        ImGui::TextColored(C_DIM, "%s", !strcmp(g, "Picture") ? "Only how it looks, never the game. Online, each player's own."
                                      : !strcmp(g, "Sound")   ? "Only how it sounds, never the game. Online, each player's own."
                                                              : "These change the game.   * = changed from the cartridge.   Online, the host's apply to everyone.");
        for (int i : display_order())
            if (!strcmp(group_of(i), g)) option_row(S, i);
    }
    ImGui::EndChild();
    ImGui::BeginChild("help", ImVec2(0, 84), ImGuiChildFlags_Borders, ImGuiWindowFlags_NoScrollbar);
    int f = -1;
    for (int i = 0; i < options_count(); i++)
        if (S.focus == options_name(i)) f = i;
    if (f >= 0) {
        const Shown *sh = shown(options_name(f));
        ImGui::TextColored(C_ACCENT, "%s", sh ? sh->label : options_name(f));
        ImGui::PushTextWrapPos(0);
        ImGui::TextUnformatted(sh ? sh->help : options_what(f));
        ImGui::PopTextWrapPos();
    } else {
        ImGui::TextColored(C_DIM, "Point at an option (or move to it with the arrow keys or a controller) to see what it does.");
    }
    ImGui::EndChild();
}

void play_page(State &S)
{
    ImGui::SeparatorText("Your game");
    ImGui::SetNextItemWidth(-150);
    if (ImGui::InputText("##rom", S.rom, sizeof S.rom)) check_rom(S);
    ImGui::SameLine();
    if (ImGui::Button("Browse...", ImVec2(-1, 0))) {
        char path[4096];
        if (host_pick_rom(path, sizeof path)) { snprintf(S.rom, sizeof S.rom, "%s", path); check_rom(S); }
    }
    if (S.rom_why.empty()) ImGui::TextColored(C_OK, "Verified: X-Men 2: Clone Wars, USA/Europe cartridge");
    else {
        ImGui::PushStyleColor(ImGuiCol_Text, C_BAD);
        ImGui::PushTextWrapPos(0);
        ImGui::TextUnformatted(S.rom_why.c_str());
        ImGui::PopTextWrapPos();
        ImGui::PopStyleColor();
    }
    ImGui::Spacing();
    ImGui::SeparatorText("Changed from the defaults");
    int n = 0;
    for (int i = 0; i < options_count(); i++) {
        std::string cur = options_get(i);
        if (cur == options_values(i)[0]) continue;
        const Shown *sh = shown(options_name(i));
        ImGui::BulletText("%s: %s", sh ? sh->label : options_name(i),
                          sh && sh->checkbox ? (cur == "1" ? "on" : "off") : value_label(i, cur).c_str());
        n++;
    }
    if (!n) ImGui::TextColored(C_DIM, "Nothing: the game plays exactly like the cartridge.");
    if (ImGui::Button("Change options...")) S.want_tab = TAB_OPTIONS;
    ImGui::SameLine();
    if (ImGui::Button("Reset everything to the defaults"))
        for (int i = 0; i < options_count(); i++) options_set(i, options_values(i)[0]);
    ImGui::Spacing();
    ImGui::SeparatorText("Controls");
    if (ImGui::BeginTable("ctl", 3, ImGuiTableFlags_SizingStretchProp)) {
        static const char *const rows[][3] = {{"", "Keyboard (player 1)", "Controller (players 1-4)"},
                                              {"Move", "Arrow keys", "D-pad or left stick"},
                                              {"A  B  C", "Z  X  C", "X  A  B"},
                                              {"X  Y  Z", "A  S  D", "LB  Y  RB"},
                                              {"Start / Mode", "Enter / Q", "Start / Back"},
                                              {"While playing", "F9 frame rate, F10 16:9, F11 fullscreen, Esc quit", ""}};
        for (int r = 0; r < 6; r++) {
            ImGui::TableNextRow();
            for (int c = 0; c < 3; c++) {
                ImGui::TableSetColumnIndex(c);
                if (r == 0 || c == 0) ImGui::TextColored(C_DIM, "%s", rows[r][c]); else ImGui::TextUnformatted(rows[r][c]);
            }
        }
        ImGui::EndTable();
    }
}

