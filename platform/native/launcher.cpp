/* the host's game takes the players */
void raise_players(int players)
{
    if (players <= 2) return;
    for (int i = 0; i < options_count(); i++)
        if (!strcmp(options_name(i), "players") && atoi(options_get(i).c_str()) < players) options_set(i, std::to_string(players));
}

/* the press -> the plan, or why not (S.error) */
bool make_plan(State &S, LaunchPlan *plan)
{
    S.error.clear();
    check_rom(S);
    if (!S.rom_why.empty()) { S.error = S.rom_why; return false; }
    plan->rom = S.rom;
    plan->netplay.clear();
    if (S.press == PRESS_PLAY) return true;
    int players = S.mode ? S.join_players : S.host_players;
    int seat = S.mode ? S.join_seat : 0;
    int port = atoi(S.port);
    if (S.connection == CONN_ICE) {
        if (!S.dir[0]) { S.error = "Choose the shared folder both players can reach."; return false; }
        plan->netplay = {"--netplay", "ice", "--seat", std::to_string(seat), "--seats", "2", "--ice-signal-dir", S.dir};
        return true;
    }
    if (port < 1 || port > 65535) { S.error = "The port is a number from 1 to 65535 (7000 if unsure)."; return false; }
    std::string peer;
    if (S.connection == CONN_CODE) {   /* the room has settled the seats */
        if (S.room) {
            RoomHostStatus st;
            room_host_status(S.room, &st);
            players = st.seats;
        } else if (S.join) {
            RoomJoinStatus st;
            room_join_status(S.join, &st);
            players = st.seats;
            seat = st.seat;
            peer = joinaddr_text(st.host);
        } else return false;
    } else if (S.mode) {
        peer = S.host;
        while (!peer.empty() && peer.back() == ' ') peer.pop_back();
        while (!peer.empty() && peer[0] == ' ') peer.erase(0, 1);
        if (peer.empty()) { S.error = "Type the host's address (the host's launcher lists it)."; return false; }
        if (peer.find(':') == std::string::npos) peer += ":7000";
    }
    const char *transport = players > 2 ? "hub" : "lan";
    const char *rb = getenv("XMEN2_ROOM_BIND");   /* the tests: the games on loopback too, as the rooms were */
    std::string bind = S.connection == CONN_CODE && rb && *rb ? rb : "0.0.0.0";
    plan->netplay = {"--netplay", transport, "--seat", std::to_string(seat), "--seats", std::to_string(players), "--bind",
                     bind + ":" + std::to_string(S.mode ? port + seat : port)};
    if (S.mode) {
        plan->netplay.push_back("--peer");
        plan->netplay.push_back(peer);
    } else raise_players(players);
    return true;
}

/* GET A CODE: open the room (this PC's own addresses in the code: its network's first, then a VPN's) */
void host_open(State &S)
{
    S.error.clear();
    check_rom(S);
    if (!S.rom_why.empty()) { S.error = S.rom_why; return; }
    int port = atoi(S.port);
    if (port < 1 || port > 65535) { S.error = "The port is a number from 1 to 65535 (7000 if unsure)."; return; }
    std::vector<uint32_t> local;
    for (int kind : {JA_LAN, JA_VPN, JA_INTERNET})
        for (const LocalAddr &a : S.addrs)
            if (joinaddr_kind(a.a) == kind) local.push_back(a.a);
    S.room = room_host_open((uint16_t)port, S.host_players, S.router, local);
    S.full_since = 0;
}

/* JOIN GAME with a code */
void join_open(State &S)
{
    S.error.clear();
    check_rom(S);
    if (!S.rom_why.empty()) { S.error = S.rom_why; return; }
    std::vector<JoinAddr> addrs;
    std::string why;
    if (!joincode_decode(S.code, 7000, &addrs, &why)) { S.error = why; return; }
    S.join = room_join_open(addrs);
}

void rooms_close(State &S)
{
    room_host_close(&S.room);
    room_join_close(&S.join);
    S.full_since = 0;
}

/* Every frame: the rooms' traffic. true when a room has started (the plan is made from it). A failure
   closes the room and shows why. */
bool rooms_pump(State &S)
{
    if (S.room) {
        room_host_pump(S.room);
        RoomHostStatus st;
        room_host_status(S.room, &st);
        if (st.state == RoomHostStatus::FAILED) { S.error = st.why; rooms_close(S); return false; }
        if (st.state == RoomHostStatus::STARTED) return true;
        if (st.state == RoomHostStatus::OPEN && (int)st.guests.size() + 1 >= S.host_players) {   /* everyone's in */
            double now = SDL_GetTicks() / 1000.0;
            if (!S.full_since) S.full_since = now;
            else if (now - S.full_since >= 1.0) room_host_start(S.room);
        } else S.full_since = 0;
    }
    if (S.join) {
        room_join_pump(S.join);
        RoomJoinStatus st;
        room_join_status(S.join, &st);
        if (st.state == RoomJoinStatus::FAILED) { S.error = st.why; rooms_close(S); return false; }
        if (st.state == RoomJoinStatus::GO) return true;
    }
    return false;
}

