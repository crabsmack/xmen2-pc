void players_combo(const char *id, int *players)
{
    static const char *const names[] = {"2", "3", "4"};
    char cur[48];
    snprintf(cur, sizeof cur, "%d%s", *players, *players == 2 ? " (you and one other)" : *players == 3 ? " (you and two others)" : " (you and three others)");
    if (ImGui::BeginCombo(id, cur)) {
        for (int k = 0; k < 3; k++)
            if (ImGui::Selectable(names[k], *players == k + 2)) *players = k + 2;
        ImGui::EndCombo();
    }
}

void connection_combo(State &S, int players)
{
    const char *names[] = {"Direct (LAN, VPN or forwarded port)", "Through routers (ICE, two players)"};
    if (players > 2) S.connection = 0;
    if (ImGui::BeginCombo("##conn", names[S.connection])) {
        if (ImGui::Selectable(names[0], S.connection == 0)) S.connection = 0;
        if (players == 2 && ImGui::Selectable(names[1], S.connection == 1)) S.connection = 1;
        ImGui::EndCombo();
    }
}

void online_page(State &S)
{
    if (ImGui::RadioButton("Host a game", S.mode == 0)) S.mode = 0;
    ImGui::SameLine(0, 30);
    if (ImGui::RadioButton("Join a game", S.mode == 1)) S.mode = 1;
    ImGui::Spacing();
    if (S.mode == 0) {
        ImGui::SeparatorText("Host");
        field_label("Players");
        players_combo("##np", &S.host_players);
        field_label("Connection");
        connection_combo(S, S.host_players);
        if (S.connection == 0) {
            field_label("Port (UDP)");
            ImGui::SetNextItemWidth(120);
            ImGui::InputText("##port", S.port, sizeof S.port, ImGuiInputTextFlags_CharsDecimal);
            ImGui::Spacing();
            ImGui::SeparatorText("Give the other players one of your addresses");
            if (S.addrs.empty()) ImGui::TextColored(C_DIM, "No network address found.");
            for (const auto &a : S.addrs) {
                std::string full = a.first + ":" + S.port;
                ImGui::PushID(full.c_str());
                ImGui::AlignTextToFramePadding();
                ImGui::TextUnformatted(full.c_str());
                ImGui::SameLine(250);
                ImGui::TextColored(C_DIM, "%s", a.second.c_str());
                ImGui::SameLine(ImGui::GetWindowWidth() - 120);
                if (ImGui::Button("Copy")) SDL_SetClipboardText(full.c_str());
                ImGui::PopID();
            }
            ImGui::TextColored(C_DIM, "Over the internet without a VPN: forward UDP %s on your router to this PC, and give out your", S.port);
            ImGui::TextColored(C_DIM, "public address (a \"what is my IP\" web page shows it).");
        } else {
            field_label("Shared folder");
            ImGui::InputText("##dir", S.dir, sizeof S.dir);
            ImGui::TextColored(C_DIM, "A folder both players can reach (a network share or a synced folder): the two games swap");
            ImGui::TextColored(C_DIM, "their connection details there, then connect through a public STUN server.");
        }
        ImGui::Spacing();
        if (S.host_players > 2) ImGui::TextColored(C_DIM, "Seats: player 2 joins as seat 1, player 3 as seat 2, player 4 as seat 3.");
        ImGui::TextColored(C_DIM, "Your game options (Gameplay, Cheats) apply to every player; picture and sound stay each player's own.");
        ImGui::TextColored(C_DIM, "Start yours first; the others then have a minute to join.");
    } else {
        ImGui::SeparatorText("Join");
        field_label("Players in the game");
        players_combo("##jp", &S.join_players);
        if (S.join_seat >= S.join_players) S.join_seat = 1;
        field_label("Connection");
        connection_combo(S, S.join_players);
        if (S.connection == 0) {
            field_label("Host's address");
            ImGui::InputTextWithHint("##host", "for example 192.168.1.20:7000", S.host, sizeof S.host);
        } else {
            field_label("Shared folder");
            ImGui::InputText("##dir", S.dir, sizeof S.dir);
        }
        if (S.join_players > 2) {
            field_label("Your seat");
            char cur[32];
            snprintf(cur, sizeof cur, "Seat %d (player %d)", S.join_seat, S.join_seat + 1);
            if (ImGui::BeginCombo("##seat", cur)) {
                for (int s = 1; s < S.join_players; s++) {
                    snprintf(cur, sizeof cur, "Seat %d (player %d)", s, s + 1);
                    if (ImGui::Selectable(cur, S.join_seat == s)) S.join_seat = s;
                }
                ImGui::EndCombo();
            }
            ImGui::TextColored(C_DIM, "Ask the host which seat is yours: each player needs a different one.");
        }
        ImGui::Spacing();
        ImGui::TextColored(C_DIM, "The host's game options apply; your picture and sound options stay yours.");
        ImGui::TextColored(C_DIM, "Everyone needs the same version of the game%s%s%s.", XMEN2_VERSION[0] ? " (this one: " : "",
                           XMEN2_VERSION, XMEN2_VERSION[0] ? ")" : "");
    }
}

void footer(State &S)
{
    ImGui::SetCursorPosY(ImGui::GetWindowHeight() - 58);
    if (!S.error.empty() && S.error != S.rom_why) {
        ImGui::SetCursorPosY(ImGui::GetWindowHeight() - 88);
        ImGui::TextColored(C_BAD, "%s", S.error.c_str());
    }
    ImGui::Separator();
    ImGui::AlignTextToFramePadding();
    ImGui::Checkbox("Show this launcher when the game starts", &S.show);
    if (ImGui::IsItemHovered())
        ImGui::SetTooltip("Off: the game starts straight away with these settings. Start it with --launcher to see this again.");
    const char *label = S.tab != TAB_ONLINE ? "PLAY" : S.mode == 0 ? "HOST GAME" : "JOIN GAME";
    float bw = 190;
    ImGui::SameLine(ImGui::GetWindowWidth() - bw - 110 - 18 - 10);
    if (ImGui::Button("Quit", ImVec2(110, 0))) S.press = PRESS_QUIT;
    ImGui::SameLine();
    bool off = !S.rom_why.empty();
    ImGui::BeginDisabled(off);
    ImGui::PushStyleColor(ImGuiCol_Button, C_ACCENT);
    ImGui::PushStyleColor(ImGuiCol_ButtonHovered, hex(0x30e830));
    ImGui::PushStyleColor(ImGuiCol_ButtonActive, hex(0x30e830));
    ImGui::PushStyleColor(ImGuiCol_Text, C_ON_ACCENT);
    if (ImGui::Button(label, ImVec2(bw, 0))) S.press = S.tab != TAB_ONLINE ? PRESS_PLAY : S.mode == 0 ? PRESS_HOST : PRESS_JOIN;
    ImGui::PopStyleColor(4);
    ImGui::EndDisabled();
    if (off && ImGui::IsItemHovered(ImGuiHoveredFlags_AllowWhenDisabled)) ImGui::SetTooltip("Choose your ROM first (Play page).");
}

void frame(State &S)
{
    ImGuiViewport *vp = ImGui::GetMainViewport();
    ImGui::SetNextWindowPos(vp->Pos);
    ImGui::SetNextWindowSize(vp->Size);
    ImGui::Begin("launcher", nullptr, ImGuiWindowFlags_NoDecoration | ImGuiWindowFlags_NoMove | ImGuiWindowFlags_NoSavedSettings |
                 ImGuiWindowFlags_NoBringToFrontOnFocus);
    ImGui::PushFont(g_title_font, 30);
    ImGui::TextColored(C_TITLE, "X-MEN 2: CLONE WARS");
    ImGui::PopFont();
    ImGui::SameLine();
    ImGui::SetCursorPosY(ImGui::GetCursorPosY() + 12);
    ImGui::TextColored(C_DIM, "for PC%s%s", XMEN2_VERSION[0] ? "  " : "", XMEN2_VERSION);
    float body_h = ImGui::GetWindowHeight() - ImGui::GetCursorPosY() - 110 - (S.error.empty() || S.error == S.rom_why ? 0 : 30);
    if (ImGui::BeginTabBar("tabs")) {
        static const char *const names[] = {"Play", "Options", "Online"};
        for (int t = 0; t < 3; t++) {
            ImGuiTabItemFlags fl = S.want_tab == t ? ImGuiTabItemFlags_SetSelected : 0;
            if (ImGui::BeginTabItem(names[t], nullptr, fl)) {
                S.tab = t;
                if (t == TAB_OPTIONS) options_page(S, body_h);
                else {
                    ImGui::BeginChild("body", ImVec2(0, body_h));
                    if (t == TAB_PLAY) play_page(S); else online_page(S);
                    ImGui::EndChild();
                }
                ImGui::EndTabItem();
            }
        }
        S.want_tab = -1;
        ImGui::EndTabBar();
    }
    footer(S);
    ImGui::End();
    bezel();
}

/* ---- remembering it (xmen2.ini [launcher], [netplay]) ------------------------------------------- */

void load(State &S, const std::string &rom)
{
    snprintf(S.rom, sizeof S.rom, "%s", rom.c_str());
    check_rom(S);
    S.show = options_ini_get("launcher", "show", "1") != "0";
    S.mode = options_ini_get("netplay", "mode", "host") == "join";
    S.host_players = atoi(options_ini_get("netplay", "players", "2").c_str());
    if (S.host_players < 2 || S.host_players > 4) S.host_players = 2;
    S.join_players = S.host_players;
    S.join_seat = atoi(options_ini_get("netplay", "seat", "1").c_str());
    if (S.join_seat < 1 || S.join_seat >= S.join_players) S.join_seat = 1;
    S.connection = options_ini_get("netplay", "connection", "direct") == "ice";
    snprintf(S.port, sizeof S.port, "%s", options_ini_get("netplay", "port", "7000").c_str());
    snprintf(S.host, sizeof S.host, "%s", options_ini_get("netplay", "host", "").c_str());
    snprintf(S.dir, sizeof S.dir, "%s", options_ini_get("netplay", "folder", "").c_str());
    S.addrs = local_addresses();
}

bool save(State &S)
{
    bool ok = options_save();
    ok &= options_ini_write("launcher", {{"show", S.show ? "1" : "0"}},
                            "show = 0: the game starts without the launcher (start it with --launcher to see it again)");
    if (S.press == PRESS_HOST || S.press == PRESS_JOIN)
        ok &= options_ini_write("netplay", {{"mode", S.mode ? "join" : "host"},
                                            {"players", std::to_string(S.mode ? S.join_players : S.host_players)},
                                            {"seat", std::to_string(S.join_seat)},
                                            {"connection", S.connection ? "ice" : "direct"},
                                            {"port", S.port}, {"host", S.host}, {"folder", S.dir}},
                                "the launcher's online settings, as last used");
    ok &= options_remember_rom(S.rom);
    return ok;
}

/* the press -> the plan, or why not (S.error) */
bool make_plan(State &S, LaunchPlan *plan)
{
    S.error.clear();
    check_rom(S);
    if (!S.rom_why.empty()) { S.error = S.rom_why; return false; }
    plan->rom = S.rom;
    plan->netplay.clear();
    if (S.press == PRESS_PLAY) return true;
    int players = S.mode ? S.join_players : S.host_players;
    int seat = S.mode ? S.join_seat : 0;
    int port = atoi(S.port);
    if (S.connection == 1) {
        if (!S.dir[0]) { S.error = "Choose the shared folder both players can reach."; return false; }
        plan->netplay = {"--netplay", "ice", "--seat", std::to_string(seat), "--seats", "2", "--ice-signal-dir", S.dir};
        return true;
    }
    if (port < 1 || port > 65535) { S.error = "The port is a number from 1 to 65535 (7000 if unsure)."; return false; }
    const char *transport = players > 2 ? "hub" : "lan";
    plan->netplay = {"--netplay", transport, "--seat", std::to_string(seat), "--seats", std::to_string(players), "--bind",
                     "0.0.0.0:" + std::to_string(S.mode ? port + seat : port)};
    if (S.mode) {
        std::string h = S.host;
        while (!h.empty() && h.back() == ' ') h.pop_back();
        while (!h.empty() && h[0] == ' ') h.erase(0, 1);
        if (h.empty()) { S.error = "Type the host's address (the host's launcher lists it)."; return false; }
        if (h.find(':') == std::string::npos) h += ":7000";
        plan->netplay.push_back("--peer");
        plan->netplay.push_back(h);
    } else if (players > 2) {
        for (int i = 0; i < options_count(); i++)   /* the host's game takes the players */
            if (!strcmp(options_name(i), "players") && atoi(options_get(i).c_str()) < players) options_set(i, std::to_string(players));
    }
    return true;
}

/* ---- XMEN2_LAUNCHER_TEST ----------------------------------------------------------------------- */

void save_shot(SDL_Renderer *r, const char *path)
{
    int w, h;
    SDL_GetRendererOutputSize(r, &w, &h);
    SDL_Surface *s = SDL_CreateRGBSurfaceWithFormat(0, w, h, 32, SDL_PIXELFORMAT_ARGB8888);
    if (!s) return;
    if (SDL_RenderReadPixels(r, nullptr, SDL_PIXELFORMAT_ARGB8888, s->pixels, s->pitch) == 0) SDL_SaveBMP(s, path);
    SDL_FreeSurface(s);
}

/* one command of the test script; a `shot` is taken after the frame is drawn */
void test_command(State &S, const std::string &line, std::string *shot)
{
    size_t sp = line.find(' ');
    std::string cmd = line.substr(0, sp), arg = sp == std::string::npos ? "" : line.substr(sp + 1);
    std::string a1 = arg.substr(0, arg.find(' ')), a2 = arg.find(' ') == std::string::npos ? "" : arg.substr(arg.find(' ') + 1);
    if (cmd == "tab") S.want_tab = a1 == "options" ? TAB_OPTIONS : a1 == "online" ? TAB_ONLINE : TAB_PLAY;
    else if (cmd == "mode") S.mode = a1 == "join";
    else if (cmd == "set") {
        for (int i = 0; i < options_count(); i++)
            if (a1 == options_name(i) && !options_set(i, a2)) fprintf(stderr, "[launcher] test: %s=%s refused\n", a1.c_str(), a2.c_str());
    } else if (cmd == "field") {
        if (a1 == "players") S.host_players = S.join_players = atoi(a2.c_str());
        else if (a1 == "connection") S.connection = a2 == "ice";
        else if (a1 == "port") snprintf(S.port, sizeof S.port, "%s", a2.c_str());
        else if (a1 == "host") snprintf(S.host, sizeof S.host, "%s", a2.c_str());
        else if (a1 == "seat") S.join_seat = atoi(a2.c_str());
        else if (a1 == "dir") snprintf(S.dir, sizeof S.dir, "%s", a2.c_str());
    } else if (cmd == "rom") { snprintf(S.rom, sizeof S.rom, "%s", arg.c_str()); check_rom(S); }
    else if (cmd == "show") S.show = a1 != "0";
    else if (cmd == "focus") S.focus = a1;
    else if (cmd == "shot") *shot = arg;
    else if (cmd == "press") S.press = a1 == "play" ? PRESS_PLAY : a1 == "host" ? PRESS_HOST : a1 == "join" ? PRESS_JOIN : PRESS_QUIT;
}

